import { Receipt, Trash2, Eye } from "lucide-react";
import { useState } from "react";
import { Card, EmptyState } from "../ui.jsx";
import { del, useApi } from "../api.js";

export default function Bills() {
  const { data: bills, reload } = useApi("/api/bills", [], 8000);
  const [detail, setDetail] = useState(null);

  async function remove(id) {
    await del(`/api/bills/${id}`);
    reload();
  }

  const statusStyle = {
    draft: "bg-saffron/10 text-saffron ring-saffron/25",
    final: "bg-mint/10 text-mint ring-mint/25",
  };

  return (
    <div className="mx-auto max-w-5xl p-6 lg:p-8">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight">Bills</h1>
        <p className="mt-1 text-sm text-dim">
          Bills generated by the agent during voice calls. Say "bill banao" to start one.
        </p>
      </header>

      <Card className="mt-6 overflow-hidden p-0">
        <div className="overflow-x-auto">
          <table className="w-full min-w-[640px] text-left text-sm">
            <thead>
              <tr className="border-b border-line text-xs text-dim">
                {["Bill #", "Customer", "Channel", "Status", "Total", "Created", ""].map((h) => (
                  <th key={h} className="px-5 py-3.5 font-medium">{h}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {bills.map((b) => (
                <tr key={b.id} className="border-b border-line/50 last:border-0 hover:bg-panel-2">
                  <td className="px-5 py-4">
                    <div className="flex items-center gap-2.5">
                      <span className="grid size-8 shrink-0 place-items-center rounded-lg bg-violet/10 ring-1 ring-violet/25">
                        <Receipt className="size-4 text-violet-soft" />
                      </span>
                      <span className="font-medium">{b.billNumber}</span>
                    </div>
                  </td>
                  <td className="px-5 py-4">{b.customerName}</td>
                  <td className="px-5 py-4 text-dim text-xs capitalize">{b.channel}</td>
                  <td className="px-5 py-4">
                    <span className={`inline-block rounded-full px-2 py-0.5 text-xs ring-1 ${statusStyle[b.status] || statusStyle.draft}`}>
                      {b.status}
                    </span>
                  </td>
                  <td className="px-5 py-4 font-semibold">₹{b.total?.toFixed(0)}</td>
                  <td className="px-5 py-4 text-dim text-xs">{b.time}</td>
                  <td className="px-5 py-4 text-right">
                    <div className="flex justify-end gap-1.5">
                      <button
                        onClick={() => setDetail(b.id)}
                        className="rounded-lg border border-line px-2 py-1.5 text-dim transition hover:text-violet-soft"
                        aria-label="View bill"
                      >
                        <Eye className="size-3.5" />
                      </button>
                      <button
                        onClick={() => remove(b.id)}
                        className="rounded-lg border border-line px-2 py-1.5 text-dim transition hover:text-rose"
                        aria-label="Delete bill"
                      >
                        <Trash2 className="size-3.5" />
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
              {bills.length === 0 && (
                <tr>
                  <td colSpan={7}>
                    <EmptyState
                      icon={Receipt}
                      title="No bills yet"
                      sub='During a web call, say "bill banao" and the agent will create one, asking for items one by one.'
                    />
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </Card>

      {/* Bill detail modal */}
      {detail && <BillDetailModal billId={detail} onClose={() => setDetail(null)} />}
    </div>
  );
}

function BillDetailModal({ billId, onClose }) {
  const { data: bill } = useApi(`/api/bills/${billId}`, null, 0);

  if (!bill) return null;

  return (
    <div className="fixed inset-0 z-50 grid place-items-center bg-black/60 p-4" onClick={onClose}>
      <div
        className="w-full max-w-lg rounded-2xl border border-line bg-panel p-6"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="flex items-start justify-between">
          <div>
            <h2 className="text-lg font-semibold">{bill.billNumber}</h2>
            <p className="text-sm text-dim">
              {bill.customerName} · {bill.customerPhone}
            </p>
          </div>
          <span className={`rounded-full px-2 py-0.5 text-xs ring-1 ${
            bill.status === "final" ? "bg-mint/10 text-mint ring-mint/25" : "bg-saffron/10 text-saffron ring-saffron/25"
          }`}>
            {bill.status}
          </span>
        </div>

        {/* Line items */}
        <div className="mt-4 rounded-xl border border-line overflow-hidden">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-line bg-panel-2 text-xs text-dim">
                <th className="px-4 py-2.5 text-left font-medium">Item</th>
                <th className="px-4 py-2.5 text-right font-medium">Qty</th>
                <th className="px-4 py-2.5 text-right font-medium">Rate</th>
                <th className="px-4 py-2.5 text-right font-medium">GST%</th>
                <th className="px-4 py-2.5 text-right font-medium">Amount</th>
              </tr>
            </thead>
            <tbody>
              {(bill.items || []).map((item) => (
                <tr key={item.id} className="border-b border-line/50 last:border-0">
                  <td className="px-4 py-2.5">{item.name}</td>
                  <td className="px-4 py-2.5 text-right">{item.quantity}</td>
                  <td className="px-4 py-2.5 text-right">₹{item.rate}</td>
                  <td className="px-4 py-2.5 text-right text-dim">{item.gst}%</td>
                  <td className="px-4 py-2.5 text-right font-medium">₹{item.amount}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* Totals */}
        <div className="mt-3 space-y-1.5 text-right text-sm">
          <p className="text-dim">Subtotal: <span className="text-white">₹{bill.subtotal?.toFixed(2)}</span></p>
          <p className="text-dim">GST: <span className="text-white">₹{bill.gstTotal?.toFixed(2)}</span></p>
          <p className="text-base font-semibold">
            Total: <span className="text-mint">₹{bill.total?.toFixed(2)}</span>
          </p>
        </div>

        <div className="mt-5 flex justify-end">
          <button onClick={onClose} className="rounded-lg border border-line px-4 py-2 text-sm text-dim hover:text-white">
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
